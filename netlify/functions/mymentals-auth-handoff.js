/* =====================================================
   mymentals-auth-handoff.js — Netlify Serverless Function
   Lets a device that requested a magic link with a requestId (see
   mymentals-auth-request.js) poll for the session once the link has
   been opened and verified elsewhere. This is what makes sign-in
   seamless on iOS: the emailed link always opens in Safari, a
   storage context separate from an installed Home Screen app, so the
   app that asked for the link can't just read the session Safari
   ends up with — it polls this endpoint instead and signs itself in
   with what comes back.

   One-time read: the first successful poll consumes the handoff, so
   a stale requestId can't be replayed to fetch someone's session
   after the fact.

   Expected query string:
     requestId — the id generated by the device that requested the link
   ===================================================== */

const { connectLambda } = require('@netlify/blobs')
const { json, consumeHandoff } = require('./mymentals-lib/session')

exports.handler = async function (event) {
  connectLambda(event) // required for getStore() to find its blobs context outside `netlify dev`

  if (event.httpMethod !== 'GET') {
    return json(405, { error: 'Method Not Allowed' })
  }

  const requestId = String(event.queryStringParameters?.requestId || '')
  if (!requestId) return json(400, { error: 'requestId is required.' })

  const session = await consumeHandoff(requestId)
  if (!session) return json(404, { error: 'Not ready yet.' })

  return json(200, session)
}
